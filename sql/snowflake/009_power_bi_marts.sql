CREATE OR REPLACE VIEW DIM_DATE AS
WITH DATES AS (
  SELECT REQUEST_DATE AS DATE_VALUE FROM AMN_DEV.CURATED.STAFFING_REQUESTS
  UNION
  SELECT ASSIGNMENT_START_DATE FROM AMN_DEV.CURATED.STAFFING_REQUESTS
  UNION
  SELECT ASSIGNMENT_END_DATE FROM AMN_DEV.CURATED.STAFFING_REQUESTS
  UNION
  SELECT APPLICATION_DATE FROM AMN_DEV.CURATED.CANDIDATES
  UNION
  SELECT WORK_DATE FROM AMN_DEV.CURATED.SCHEDULES
)
SELECT
  DATE_VALUE AS FULL_DATE,
  YEAR(DATE_VALUE) AS YEAR_NUMBER,
  QUARTER(DATE_VALUE) AS QUARTER_NUMBER,
  MONTH(DATE_VALUE) AS MONTH_NUMBER,
  MONTHNAME(DATE_VALUE) AS MONTH_NAME,
  WEEKOFYEAR(DATE_VALUE) AS WEEK_NUMBER,
  DAYOFMONTH(DATE_VALUE) AS DAY_OF_MONTH,
  DAYNAME(DATE_VALUE) AS DAY_NAME
FROM DATES
WHERE DATE_VALUE IS NOT NULL;

CREATE OR REPLACE VIEW FACT_STAFFING_REQUEST AS
WITH CANDIDATE_SUMMARY AS (
  SELECT
    REQUEST_ID,
    COUNT(*) AS CANDIDATE_COUNT,
    COUNT_IF(EMPLOYEE_ID IS NOT NULL) AS PLACED_CANDIDATE_COUNT,
    COUNT_IF(UPPER(CANDIDATE_STATUS) IN ('AVAILABLE', 'ACTIVE', 'QUALIFIED')) AS AVAILABLE_CANDIDATE_COUNT
  FROM AMN_DEV.CURATED.CANDIDATES
  GROUP BY REQUEST_ID
),
SCHEDULE_SUMMARY AS (
  SELECT
    REQUEST_ID,
    COUNT(*) AS SCHEDULE_COUNT,
    SUM(COALESCE(PLANNED_HOURS, 0)) AS PLANNED_HOURS,
    SUM(COALESCE(WORKED_HOURS, 0)) AS WORKED_HOURS,
    SUM(COALESCE(OVERTIME_HOURS, 0)) AS OVERTIME_HOURS
  FROM AMN_DEV.CURATED.SCHEDULES
  GROUP BY REQUEST_ID
)
SELECT
  R.REQUEST_ID,
  R.HOSPITAL_ID,
  R.HOSPITAL_NAME,
  R.CITY,
  R.STATE,
  R.REQUIRED_ROLE,
  R.DEPARTMENT,
  R.EMPLOYMENT_TYPE,
  R.SHIFT_PREFERENCE,
  R.REQUIRED_STAFF,
  R.FILLED_STAFF,
  R.OPEN_POSITIONS,
  R.PRIORITY,
  R.REQUEST_STATUS,
  R.REQUEST_DATE,
  R.ASSIGNMENT_START_DATE,
  R.ASSIGNMENT_END_DATE,
  R.DURATION_WEEKS,
  R.HOURLY_BILL_RATE,
  IFF(UPPER(R.REQUEST_STATUS) IN ('OPEN', 'PENDING', 'IN PROGRESS'), TRUE, FALSE) AS IS_OPEN_REQUEST,
  IFF(COALESCE(R.REQUIRED_STAFF, 0) = 0, NULL,
      R.FILLED_STAFF / R.REQUIRED_STAFF::NUMBER(18, 4)) AS FILL_RATE,
  IFF(COALESCE(R.FILLED_STAFF, 0) > 0 AND R.ASSIGNMENT_START_DATE IS NOT NULL,
      DATEDIFF('day', R.REQUEST_DATE, R.ASSIGNMENT_START_DATE), NULL) AS TIME_TO_FILL_DAYS,
  COALESCE(C.CANDIDATE_COUNT, 0) AS CANDIDATE_COUNT,
  COALESCE(C.PLACED_CANDIDATE_COUNT, 0) AS ACTIVE_PLACEMENT_COUNT,
  COALESCE(C.AVAILABLE_CANDIDATE_COUNT, 0) AS AVAILABLE_CANDIDATE_COUNT,
  COALESCE(S.SCHEDULE_COUNT, 0) AS SCHEDULE_COUNT,
  COALESCE(S.PLANNED_HOURS, 0) AS PLANNED_HOURS,
  COALESCE(S.WORKED_HOURS, 0) AS WORKED_HOURS,
  COALESCE(S.OVERTIME_HOURS, 0) AS OVERTIME_HOURS
FROM AMN_DEV.CURATED.STAFFING_REQUESTS R
LEFT JOIN CANDIDATE_SUMMARY C ON R.REQUEST_ID = C.REQUEST_ID
LEFT JOIN SCHEDULE_SUMMARY S ON R.REQUEST_ID = S.REQUEST_ID;

CREATE OR REPLACE VIEW FACT_PLACEMENT_SCHEDULE AS
SELECT
  S.SCHEDULE_ID,
  S.EMPLOYEE_ID,
  S.REQUEST_ID,
  S.HOSPITAL_ID,
  S.HOSPITAL_NAME,
  S.WORK_DATE,
  S.SHIFT_TYPE,
  S.SHIFT_START_TIME,
  S.SHIFT_END_TIME,
  S.PLANNED_HOURS,
  S.WORKED_HOURS,
  S.OVERTIME_HOURS,
  S.SCHEDULE_STATUS,
  R.REQUIRED_ROLE,
  R.DEPARTMENT,
  R.STATE,
  C.CANDIDATE_ID,
  C.RECRUITER_ID,
  C.PROFESSION
FROM AMN_DEV.CURATED.SCHEDULES S
LEFT JOIN AMN_DEV.CURATED.STAFFING_REQUESTS R ON S.REQUEST_ID = R.REQUEST_ID
LEFT JOIN AMN_DEV.CURATED.CANDIDATES C
  ON S.EMPLOYEE_ID = C.EMPLOYEE_ID
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY S.SCHEDULE_ID
  ORDER BY C.UPDATED_AT DESC NULLS LAST, C.CANDIDATE_ID
) = 1;

