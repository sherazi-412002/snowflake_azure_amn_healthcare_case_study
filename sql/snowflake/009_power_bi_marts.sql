CREATE OR REPLACE VIEW VW_RECRUITING_FUNNEL AS
SELECT
  APPLICATION_DATE,
  HOSPITAL_ID,
  RECRUITER_ID,
  PROFESSION,
  DEPARTMENT,
  LICENSE_STATE,
  SOURCE_CHANNEL,
  CANDIDATE_STATUS,
  BACKGROUND_CHECK_STATUS,
  CREDENTIAL_STATUS,
  COUNT(*) AS CANDIDATE_COUNT,
  COUNT_IF(EMPLOYEE_ID IS NOT NULL) AS PLACEMENT_COUNT
FROM AMN_DEV.CURATED.CANDIDATES
GROUP BY ALL;

CREATE OR REPLACE VIEW VW_EXECUTIVE_KPIS AS
SELECT
  COUNT(*) AS TOTAL_REQUESTS,
  COUNT_IF(IS_OPEN_REQUEST) AS OPEN_REQUESTS,
  SUM(COALESCE(REQUIRED_STAFF, 0)) AS REQUIRED_STAFF,
  SUM(COALESCE(FILLED_STAFF, 0)) AS FILLED_STAFF,
  SUM(COALESCE(OPEN_POSITIONS, 0)) AS OPEN_POSITIONS,
  IFF(SUM(COALESCE(REQUIRED_STAFF, 0)) = 0, NULL,
      SUM(COALESCE(FILLED_STAFF, 0)) / SUM(COALESCE(REQUIRED_STAFF, 0))::NUMBER(18, 4)) AS FILL_RATE,
  AVG(TIME_TO_FILL_DAYS) AS AVG_TIME_TO_FILL_DAYS,
  SUM(ACTIVE_PLACEMENT_COUNT) AS ACTIVE_PLACEMENTS,
  SUM(PLANNED_HOURS) AS PLANNED_HOURS,
  SUM(WORKED_HOURS) AS WORKED_HOURS,
  SUM(OVERTIME_HOURS) AS OVERTIME_HOURS
FROM FACT_STAFFING_REQUEST;

CREATE OR REPLACE VIEW VW_PIPELINE_RUNS AS
SELECT
  R.RUN_ID,
  R.BATCH_ID,
  R.SOURCE_SYSTEM,
  R.SOURCE_OBJECT,
  R.TARGET_TABLE,
  R.STATUS,
  R.EXTRACT_STARTED_AT,
  R.EXTRACT_FINISHED_AT,
  R.RAW_LOADED_AT,
  R.CURATED_AT,
  DATEDIFF('second', R.EXTRACT_STARTED_AT, R.EXTRACT_FINISHED_AT) AS RUN_DURATION_SECONDS,
  C.SLA_SECONDS,
  IFF(R.STATUS = 'SUCCEEDED'
      AND R.EXTRACT_FINISHED_AT IS NOT NULL
      AND DATEDIFF('second', R.EXTRACT_STARTED_AT, R.EXTRACT_FINISHED_AT) <= C.SLA_SECONDS,
      TRUE, FALSE) AS WITHIN_RUN_SLA,
  R.ROWS_READ,
  R.ROWS_INSERTED,
  R.ROWS_UPDATED,
  R.ROWS_DELETED,
  R.ROWS_REJECTED,
  R.RETRY_COUNT,
  R.ERROR_CATEGORY,
  R.ERROR_MESSAGE
FROM AMN_DEV.CONTROL.PIPELINE_RUN_LOG R
LEFT JOIN AMN_DEV.CONTROL.INGESTION_CONFIG C
  ON R.SOURCE_SYSTEM = C.SOURCE_SYSTEM
 AND R.SOURCE_OBJECT = C.SOURCE_OBJECT;

CREATE OR REPLACE VIEW VW_PIPELINE_LATEST_STATUS AS
SELECT *
FROM VW_PIPELINE_RUNS
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY SOURCE_SYSTEM, SOURCE_OBJECT
  ORDER BY EXTRACT_STARTED_AT DESC
) = 1;

