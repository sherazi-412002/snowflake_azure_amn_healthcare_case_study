CREATE OR REPLACE PROCEDURE CONTROL.START_HR_RUN(P_RUN_ID VARCHAR,P_BATCH_ID VARCHAR,P_OBJECT VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS $$
BEGIN
  INSERT INTO CONTROL.PIPELINE_RUN_LOG(RUN_ID,BATCH_ID,SOURCE_SYSTEM,SOURCE_OBJECT,TARGET_TABLE,EXTRACT_STARTED_AT,STATUS)
  VALUES(:P_RUN_ID,:P_BATCH_ID,'HR',:P_OBJECT,'AMN_DEV.CURATED.'||:P_OBJECT,CURRENT_TIMESTAMP(),'STARTED');
  RETURN 'STARTED';
END; $$;

CREATE OR REPLACE PROCEDURE CONTROL.SUCCEED_HR_RUN(P_RUN_ID VARCHAR,P_OBJECT VARCHAR,P_ROWS_READ NUMBER,P_ROWS_COPIED NUMBER)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS $$
BEGIN
  UPDATE CONTROL.PIPELINE_RUN_LOG SET EXTRACT_FINISHED_AT=CURRENT_TIMESTAMP(),RAW_LOADED_AT=CURRENT_TIMESTAMP(),
    CURATED_AT=CURRENT_TIMESTAMP(),ROWS_READ=:P_ROWS_READ,ROWS_INSERTED=:P_ROWS_COPIED,STATUS='SUCCEEDED'
  WHERE RUN_ID=:P_RUN_ID AND SOURCE_OBJECT=:P_OBJECT;
  RETURN 'SUCCEEDED';
END; $$;

CREATE OR REPLACE PROCEDURE CONTROL.FAIL_HR_RUN(P_RUN_ID VARCHAR,P_OBJECT VARCHAR,P_CATEGORY VARCHAR,P_MESSAGE VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS $$
BEGIN
  UPDATE CONTROL.PIPELINE_RUN_LOG SET EXTRACT_FINISHED_AT=CURRENT_TIMESTAMP(),STATUS='FAILED',
    ERROR_CATEGORY=LEFT(:P_CATEGORY,500),ERROR_MESSAGE=LEFT(:P_MESSAGE,8000)
  WHERE RUN_ID=:P_RUN_ID AND SOURCE_OBJECT=:P_OBJECT;
  RETURN 'FAILED';
END; $$;

