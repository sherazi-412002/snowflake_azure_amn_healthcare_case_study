CREATE OR REPLACE PROCEDURE CURATED.MERGE_STAFFING_REQUESTS()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS $$
BEGIN
  MERGE INTO CURATED.STAFFING_REQUESTS T USING (
    SELECT REQUEST_ID,HOSPITAL_ID,HOSPITAL_NAME,CITY,STATE,REQUIRED_ROLE,DEPARTMENT,
      EMPLOYMENT_TYPE,SHIFT_PREFERENCE,TRY_TO_NUMBER(REQUIRED_STAFF) REQUIRED_STAFF,
      TRY_TO_NUMBER(FILLED_STAFF) FILLED_STAFF,TRY_TO_NUMBER(OPEN_POSITIONS) OPEN_POSITIONS,
      PRIORITY,REQUEST_STATUS,TRY_TO_DATE(REQUEST_DATE) REQUEST_DATE,
      TRY_TO_DATE(ASSIGNMENT_START_DATE) ASSIGNMENT_START_DATE,
      TRY_TO_DATE(ASSIGNMENT_END_DATE) ASSIGNMENT_END_DATE,
      TRY_TO_NUMBER(DURATION_WEEKS) DURATION_WEEKS,TRY_TO_DECIMAL(HOURLY_BILL_RATE,12,2) HOURLY_BILL_RATE
    FROM RAW.STAFFING_REQUESTS WHERE NULLIF(TRIM(REQUEST_ID),'') IS NOT NULL
    QUALIFY ROW_NUMBER() OVER(PARTITION BY REQUEST_ID ORDER BY _INGESTED_AT DESC NULLS LAST)=1
  ) S ON T.REQUEST_ID=S.REQUEST_ID
  WHEN MATCHED THEN UPDATE SET HOSPITAL_ID=S.HOSPITAL_ID,HOSPITAL_NAME=S.HOSPITAL_NAME,CITY=S.CITY,
    STATE=S.STATE,REQUIRED_ROLE=S.REQUIRED_ROLE,DEPARTMENT=S.DEPARTMENT,EMPLOYMENT_TYPE=S.EMPLOYMENT_TYPE,
    SHIFT_PREFERENCE=S.SHIFT_PREFERENCE,REQUIRED_STAFF=S.REQUIRED_STAFF,FILLED_STAFF=S.FILLED_STAFF,
    OPEN_POSITIONS=S.OPEN_POSITIONS,PRIORITY=S.PRIORITY,REQUEST_STATUS=S.REQUEST_STATUS,
    REQUEST_DATE=S.REQUEST_DATE,ASSIGNMENT_START_DATE=S.ASSIGNMENT_START_DATE,
    ASSIGNMENT_END_DATE=S.ASSIGNMENT_END_DATE,DURATION_WEEKS=S.DURATION_WEEKS,
    HOURLY_BILL_RATE=S.HOURLY_BILL_RATE,UPDATED_AT=CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (REQUEST_ID,HOSPITAL_ID,HOSPITAL_NAME,CITY,STATE,REQUIRED_ROLE,DEPARTMENT,
    EMPLOYMENT_TYPE,SHIFT_PREFERENCE,REQUIRED_STAFF,FILLED_STAFF,OPEN_POSITIONS,PRIORITY,REQUEST_STATUS,
    REQUEST_DATE,ASSIGNMENT_START_DATE,ASSIGNMENT_END_DATE,DURATION_WEEKS,HOURLY_BILL_RATE)
  VALUES(S.REQUEST_ID,S.HOSPITAL_ID,S.HOSPITAL_NAME,S.CITY,S.STATE,S.REQUIRED_ROLE,S.DEPARTMENT,
    S.EMPLOYMENT_TYPE,S.SHIFT_PREFERENCE,S.REQUIRED_STAFF,S.FILLED_STAFF,S.OPEN_POSITIONS,S.PRIORITY,
    S.REQUEST_STATUS,S.REQUEST_DATE,S.ASSIGNMENT_START_DATE,S.ASSIGNMENT_END_DATE,S.DURATION_WEEKS,S.HOURLY_BILL_RATE);
  RETURN 'SUCCEEDED';
END; $$;

